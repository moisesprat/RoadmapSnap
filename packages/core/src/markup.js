/**
 * Returns the trimmed value only when it is an absolute http: or https: URL, otherwise null. Used before a
 * stored link becomes an href, so javascript:, data:, vbscript:, file: and relative values never reach one.
 * @param {unknown} value
 * @returns {string | null}
 */
export function safeHttpUrl(value) {
    if (typeof value !== 'string') return null;
    const trimmed = value.trim();
    if (trimmed === '') return null;
    try {
        const url = new URL(trimmed);
        return url.protocol === 'http:' || url.protocol === 'https:' ? trimmed : null;
    } catch {
        return null;
    }
}
